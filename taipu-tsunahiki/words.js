/* 小さな たねから きまった ならびの 数を 出します（2人の 画面で そろえる ため）*/
function seeded(seed) {
    let a = seed >>> 0;
    return () => {
        a = (a + 0x6D2B79F5) >>> 0;
        let t = a;
        t = Math.imul(t ^ (t >>> 15), t | 1);
        t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}

/**
 * たいせんで つかう ことばの ならびを 作ります。
 * おなじ たねなら、どの 画面でも おなじ ならびに なります。
 * ぜんぶ 打ちおわったら、また ならべなおして つづけます。
 */
export function wordList(level, seed, count = 200) {
    const base = WORDS[level] || WORDS.easy;
    const rnd = seeded(seed);
    const out = [];
    while (out.length < count) {
        const a = base.slice();
        for (let i = a.length - 1; i > 0; i--) {
            const j = Math.floor(rnd() * (i + 1));
            [a[i], a[j]] = [a[j], a[i]];
        }
        /* つなぎめで おなじ ことばが つづかない ように */
        if (out.length && a[0] === out[out.length - 1]) a.push(a.shift());
        out.push(...a);
    }
    return out.slice(0, count);
}
