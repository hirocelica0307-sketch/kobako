/* =========================================================
   カテゴリの え（100×100 の 中に かく。heroAt で 大きさを あわせる）
   ========================================================= */
function heroAt(key, x, y, w, h) {
  const fn = HEROES[key];
  if (!fn) return '';
  const s = Math.min(w, h) / 100;
  return scaled(x + (w - 100 * s) / 2, y + (h - 100 * s) / 2, s, fn);
}

function mapleLeaf(cx, cy, r, rot = 0) {
  const pts = [];
  for (let i = 0; i < 70; i++) {
    const a = i / 70 * Math.PI * 2;
    const lobe = Math.abs(Math.cos(a * 3.5));
    const rr = r * (0.45 + 0.55 * Math.pow(lobe, 0.6)) * (a > Math.PI * 0.35 && a < Math.PI * 0.65 ? 0.55 : 1);
    const spike = i % 2 ? 0.93 : 1;
    pts.push([cx + rr * spike * Math.cos(a - Math.PI / 2 + rot), cy + rr * spike * Math.sin(a - Math.PI / 2 + rot)]);
  }
  return POLY(pts, { w: 0.7 });
}

