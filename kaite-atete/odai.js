/* 「けんび」「しろい」など、絵に しにくい ものを あとから はずせるように
   したいので、リストは そのまま 配列で もっています。 */

/** ランダムに お題を 1つ えらびます。さっき 出た ものは できるだけ よけます。 */
export function pickWord(levelKey, recent = []) {
    const list = ODAI[levelKey] || ODAI.low;
    const fresh = list.filter(w => !recent.includes(w));
    const from = fresh.length ? fresh : list;
    return from[Math.floor(Math.random() * from.length)];
}

/** こたえを くらべる ための かたちに そろえます。
    カタカナは ひらがなに、すきまは とりのぞきます。 */
export function normalize(text) {
    return String(text || '')
        .replace(/[ァ-ヶ]/g, c => String.fromCharCode(c.charCodeAt(0) - 0x60))
        .replace(/[\s　]/g, '');
}

/** お題を そのまま のこすと 見えてしまうので、数字に かえて くらべます。
    （むずかしい 暗号では ありませんが、ふつうに 遊ぶ ぶんには 十分です） */
export function hashWord(text) {
    const s = normalize(text);
    let h = 0x811c9dc5;
    for (let i = 0; i < s.length; i++) {
        h ^= s.charCodeAt(i);
        h = Math.imul(h, 0x01000193) >>> 0;
    }
    return h.toString(16);
}
